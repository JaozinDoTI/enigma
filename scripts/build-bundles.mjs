import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function moduleId(filePath) {
  return path.relative(projectRoot, filePath).replaceAll('\\', '/');
}

function resolveModule(fromFile, request) {
  const resolved = path.resolve(path.dirname(fromFile), request);
  return path.extname(resolved) ? resolved : `${resolved}.js`;
}

function importBinding(clause, dependencyId) {
  const required = `__require(${JSON.stringify(dependencyId)})`;
  const value = clause.trim();
  if (value.startsWith('{')) {
    const bindings = value
      .slice(1, -1)
      .split(',')
      .map((part) => part.trim().replace(/\s+as\s+/, ': '))
      .filter(Boolean)
      .join(', ');
    return `const { ${bindings} } = ${required};`;
  }
  return `const ${value} = ${required}.default;`;
}

function transformModule(filePath, collect) {
  let source = fs.readFileSync(filePath, 'utf8');
  const namedExports = [];
  let hasDefault = false;

  source = source.replace(/^import\s+(.+?)\s+from\s+['"](.+?)['"];?\s*$/gm, (_, clause, request) => {
    const dependency = resolveModule(filePath, request);
    collect(dependency);
    return importBinding(clause, moduleId(dependency));
  });

  source = source.replace(/^export\s+(const|let|var)\s+(\w+)/gm, (_, kind, name) => {
    namedExports.push(name);
    return `${kind} ${name}`;
  });

  source = source.replace(/^export\s+(async\s+)?function\s+(\w+)/gm, (_, asyncKeyword = '', name) => {
    namedExports.push(name);
    return `${asyncKeyword}function ${name}`;
  });

  source = source.replace(/^export\s+default\s+/gm, () => {
    hasDefault = true;
    return 'const __defaultExport = ';
  });

  const assignments = namedExports.map((name) => `exports.${name} = ${name};`);
  if (hasDefault) assignments.push('exports.default = __defaultExport;');
  return `${source}\n${assignments.join('\n')}`;
}

function bundle(entryRelative, outputRelative) {
  const modules = new Map();
  const entry = path.resolve(projectRoot, entryRelative);

  function collect(filePath) {
    const id = moduleId(filePath);
    if (modules.has(id)) return;
    modules.set(id, '');
    modules.set(id, transformModule(filePath, collect));
  }

  collect(entry);
  const definitions = [...modules.entries()].map(([id, source]) => `${JSON.stringify(id)}: function(module, exports, __require) {\n${source}\n}`).join(',\n');
  const output = `/* Generated by scripts/build-bundles.mjs. Edit modular sources, then rebuild. */\n(function () {\n'use strict';\nconst __modules = {\n${definitions}\n};\nconst __cache = Object.create(null);\nfunction __require(id) {\n  if (__cache[id]) return __cache[id].exports;\n  if (!__modules[id]) throw new Error('Missing bundled module: ' + id);\n  const module = { exports: {} };\n  __cache[id] = module;\n  __modules[id](module, module.exports, __require);\n  return module.exports;\n}\n__require(${JSON.stringify(moduleId(entry))});\n})();\n`;
  fs.writeFileSync(path.resolve(projectRoot, outputRelative), output, 'utf8');
}

bundle('js/app.js', 'js/app.bundle.js');
bundle('js/node.js', 'js/node.bundle.js');
